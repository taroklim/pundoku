-- 0005_daily_puzzles_generator_version: версия алгоритма генератора в фолбэк-строках (PD-14).
-- Строка с source = 'generator' хранит сетку, сгенерированную конкретной версией движка
-- (`GENERATOR_VERSION` из @pundoku/engine). После смены версии (v1 → v2 в PD-9 и далее) такая
-- сетка устарела: офлайн-клиент новой версии посчитает другую, и они разойдутся. Сервис игнорирует
-- generator-строки с версией, отличной от текущей, и пересоздаёт их при запросе на дату.
-- NULL у generator-строки = версия неизвестна (строки до этой миграции) → считается устаревшей.
-- Для source = 'sudoku.com' колонка всегда NULL (сетка чужая и неизменна).
ALTER TABLE daily_puzzles ADD COLUMN generator_version INTEGER;
