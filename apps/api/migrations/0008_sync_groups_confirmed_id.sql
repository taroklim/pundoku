-- 0008_sync_groups_confirmed_id: идемпотентное подтверждение замены ключа (PD-126, находка QA F1 / PD-138).
-- Если ответ на confirm потерян (обрыв сети), сервер уже переключил ключ, а клиент повторяет запрос и получал 409
-- no_pending — и человек оставался в убеждении, что новый ключ не действует. Теперь у группы запоминается метка той
-- замены, которая сделала ТЕКУЩИЙ рабочий ключ рабочим: повтор confirm с этой же меткой отвечает 200 (already
-- confirmed), ничего не меняя. Метка меняется только при confirm (как и key_hmac), поэтому всегда описывает
-- именно рабочий ключ: после следующей замены прежняя метка перестаёт совпадать.
-- Только ADD COLUMN, nullable, без значений по умолчанию: существующие группы и клиенты не затрагиваются.
-- Метка — случайный UUID, известный лишь тому, кому показали ответ rotate; ключа и его HMAC здесь нет.
ALTER TABLE sync_groups ADD COLUMN confirmed_id UUID;
