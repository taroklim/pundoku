/**
 * PD-206: строка о звуке до первого хода (`.status.melody-hint`) — какая форма помещается в зазор между полем и падом.
 *
 * Зазор (`.gap`) держит в `--chrome` ОДНУ строку статуса; лишнее место у него есть, только когда поле упирается в ширину
 * (высокий экран) или остаётся резерв под док. Полная подсказка — 2–4 строки, поэтому при крупном шрифте (с xxxL, 23 px) и
 * на AX3 она налезала на поле и пад (QA PD-204). Решение — по прецеденту статус-строки (PD-144 `.st-short`, PD-147 строка
 * Ink): поле от подсказки не зависит вовсе (зазор — size-контейнер, его размер не считается от содержимого, исчезновение
 * подсказки на первом ходу ничего не двигает), а форма выбирается контейнер-запросом по месту, которое у зазора есть:
 *
 * - `long` — полная строка, только если ширина гарантирует ≤ 4 / ≤ 3 / ≤ 2 строки и зазор держит столько строк;
 * - `short` — короткая форма в одну строку («Каждая цифра — нота»), без переноса;
 * - `none` — места нет и на неё (AX3, 30 px на 320 pt): вместо подсказки — короткое «осталось N», как у статус-строки при AX3.
 *
 * AX3 (`:root[data-type="ax3"]`) — всегда `none`, явно. Полный текст всегда остаётся доступным именем (clip-path).
 * Числа — те же, что в styles/melody.css (тест `melody.css.test.ts` держит их вместе); единица — em шрифта зазора (= rem).
 */
export const HINT_FIT = {
  /** Короткая форма в одну строку: ширина контента зазора, em. Самая длинная (ru, 9.75 em шрифта подсказки × 0.88) + значок. */
  shortMinEm: 10.2,
  /** Полная форма в ≤ 4 строки: ширина, em (ru: 11.05 em шрифта подсказки). */
  long4MinEm: 13.8,
  /** …и высота под 4 строки: 4.58 em. */
  long4MinHEm: 4.7,
  /** Полная форма в ≤ 3 строки: ширина, em (ru: 15.1 em шрифта подсказки на строку текста + значок + отступы 38 px при 13 px). */
  long3MinEm: 17.5,
  /** …и высота контента зазора под 3 строки: 3 × 0.88 × 1.3 = 3.43 em. */
  long3MinHEm: 3.5,
  /** Полная форма в ≤ 2 строки (ru: 21.6 em шрифта подсказки). */
  long2MinEm: 23,
  /** …и высота под 2 строки: 2.29 em. */
  long2MinHEm: 2.35,
} as const;

/** Высота строки подсказки в em зазора: 0.88rem × line-height 1.3. */
export const HINT_LINE_EM = 0.88 * 1.3;

export type HintForm = "long" | "short" | "none";

/** Какую форму покажет CSS для контента зазора `w × h` px при корневом шрифте `rem` px. */
export function hintForm(w: number, h: number, rem: number, ax3 = rem >= 36): HintForm {
  if (ax3) return "none";
  const we = w / rem;
  const he = h / rem;
  const fits = (minW: number, minH: number) => we >= minW && he >= minH;
  if (fits(HINT_FIT.long4MinEm, HINT_FIT.long4MinHEm) || fits(HINT_FIT.long3MinEm, HINT_FIT.long3MinHEm) || fits(HINT_FIT.long2MinEm, HINT_FIT.long2MinHEm)) return "long";
  if (we >= HINT_FIT.shortMinEm) return "short";
  return "none";
}
